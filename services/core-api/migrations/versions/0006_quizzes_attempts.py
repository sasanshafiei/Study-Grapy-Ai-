"""Quiz sessions, question assignments, graded attempts and topic practice statistics (M7).

Revision ID: 0006
Revises: 0005
Create Date: 2026-11-20

Added (docs/quiz-api.md, docs/database-migrations.md):

- topics: UNIQUE (id, course_id), the target of every composite topic key below.
- quiz_sessions: one generation request of one student in one course,
  identified by (user_id, idempotency_key), with the request fingerprint,
  the requested topics/count/difficulty/scope, and a generating -> ready |
  failed state machine (CHECK). A generating session holds an attempt token
  and a lease (database time); ready and failed are terminal. At most one
  generating session per user (partial unique index). There is deliberately
  NO foreign key to enrollments: practice history survives a later removal
  from the course; current enrollment is enforced by authorization.
- quiz_generation_quotas: per user and UTC day, the number of generations
  reserved (atomic upsert, CHECK used >= 0).
- questions: hint, answer_key, grading_method, generated_by_session_id,
  generated_for_user_id, generation, content_hash (all NULL for legacy rows),
  CHECKs on purpose/qtype/difficulty/status, a composite topic key
  (topic_id, course_id) -> topics, and for generated questions a complete-
  metadata CHECK and a composite key to their owning session and student.
  status = 'generated' if and only if the generation marker is set.
- quiz_items: the assignment of a generated question to its session and
  student at a position. Composite keys guarantee: session/user/course
  consistency, question/course/purpose consistency (purpose CHECKed to
  'practice', so an exam question can never be assigned), and that the
  question was generated by this very session for this very student.
  UNIQUE (question_id): a generated question is never reassigned.
- attempts: course_id (backfilled deterministically from questions, then
  NOT NULL), and the M7 grading columns (quiz_item_id, answer,
  grading_method, feedback, mastery_before/after, mastery_method,
  stats_attempts/correct, submitted_at). A CHECK requires all of them for an
  M7 attempt and none of them for any other attempt. A composite key
  (quiz_item_id, user_id, question_id, topic_id, course_id) -> quiz_items
  ties an M7 attempt to its assignment; UNIQUE (quiz_item_id) allows one
  attempt per assignment.
- topic_practice_stats: per (user, topic) counters of committed M7 attempts
  (CHECK 0 <= correct <= attempts), course-consistent through a composite key.

Triggers (PL/pgSQL; they are not part of the reflected-schema comparison):
- questions: a generated question can only be inserted into a `generating`
  session (its row is locked FOR SHARE, so finalizing the session and adding a
  question cannot interleave), and can never be updated or deleted; an UPDATE
  can neither set the generation marker on an existing row nor change `status`
  to or from 'generated'. Legacy and non-generated questions (future M9
  drafts) stay editable.
- quiz_items: inserted only into a `generating` session (same FOR SHARE lock);
  never updated or deleted.
- quiz_sessions: never deleted; never inserted `ready`; identity columns never
  change; ready and failed are terminal; ready requires exactly
  requested_count assignments (counted while the session row is locked).
- attempts: an M7 attempt is append-only (no UPDATE/DELETE), needs an
  assignment of a `ready` session, and is checked on insert against its
  question's answer key (deterministic grading in the database). A generated
  question can be answered only through its assignment: a legacy-style INSERT
  naming it, or an UPDATE moving a legacy attempt onto it, is refused; an
  UPDATE cannot turn a legacy attempt into an M7 attempt. Other legacy attempts
  stay editable, and a legacy-style INSERT without course_id gets it from its
  question (the same deterministic rule as the backfill).
- NULL safety: a CHECK accepts UNKNOWN. The generated branch of
  questions_generated_check and the graded branch of attempts_practice_check
  are therefore `(...) IS TRUE`; a generated question's answer_key must be
  exactly {"choice_id": <id of one of its choices>}.

Data safety:
- upgrade locks the practice tables, refuses before any change when an
  existing row would violate a new CHECK or composite key, backfills
  attempts.course_id and never changes any other existing value.
- downgrade refuses, before any change, while any M7 state exists.
Both run as SQL, so they also apply to offline (`--sql`) output.

Self-contained on purpose: it does not import app.models.
"""

