"""Local file store for uploaded documents.

Layout under the configured root (UPLOAD_DIR, a persistent Docker volume):

    <root>/<course_id>/<document_id>.pdf   stored originals
    <root>/.incoming/staged-*.part          files being received (M3 ownership protocol)
    <root>/.incoming/upload-*.part          left by an M2 upload (no ownership protocol)
    <root>/.incoming.lock                   coordinates creating and cleaning temporary files
    <root>/.studygraph-storage              identity marker (app/storage_identity.py)

Storage keys are generated by the server from two UUIDs and validated against
a strict pattern before use, so a client-supplied name never becomes part of a
path. Directories below the root are created by this module and must be real
directories, not symbolic links.

An upload is written to a temporary file in .incoming (same filesystem), then
given its final name with os.link, which fails instead of replacing an
existing file. The operation that staged a file owns it: StagedFile tracks the
temporary name and, once linked, the final name, and cleanup only ever touches
those two names. After the database commit is confirmed the caller calls
release(), and from then on nothing in this module can remove the file.

Ownership of temporary files (M3). An upload holds an exclusive flock(2) on its
file's inode from before the reconciler can see the file until the upload has
finished (committed, rolled back or given up), whatever path it exits by:

1. take .incoming.lock shared; create the temporary file (O_EXCL); open a
   second descriptor on it and lock that exclusively; release .incoming.lock.
2. keep the exclusive lock while writing, linking to the final name (the lock
   is on the inode, so it covers the final name too) and committing.
3. on exit, remove the temporary name first and release the lock last.

The reconciler (clean_abandoned_temp_files) takes .incoming.lock exclusively,
so no file can be between creation and locking while it looks, and removes a
`staged-*.part` file only if it can take the file's lock itself (no live
owner: flock locks die with their process), the file is older than a grace
period, and the name still refers to the inode it locked. Files named like M2
uploads (`upload-*.part`) never had an owner lock and are only reported.
Locks are always taken in the same order (.incoming.lock, then a file), and
the reconciler never waits for a file lock.

Durability. place() returns only after everything a committed document needs
has been fsynced, in this order: the file's data; the root directory (so the
course directory's entry exists, whoever created that directory, possibly a
concurrent upload that has not synced it yet); the course directory after the
link (so the file's name exists). The caller commits only after place()
returns, and any fsync failure raises StorageError instead. When the root
itself is created here (it normally is the Docker volume's mount point and
already exists), the parent of every directory level created is fsynced too.
The .incoming directory is not synced: a temporary name that reappears after a
crash is garbage for reconciliation, never referenced by the database.

One root (M3 review fix). The root is pinned at first use (resolved path,
st_dev, st_ino) and re-checked on every access, so the identity check, the
ownership lock, staging, placement and reads all refer to the same directory;
a retargeted symlink or a replaced mount makes them fail instead of mixing two
stores. What remains is the instant between a check and the system call that
follows it: the store is assumed to be a trusted local directory that nobody
swaps out while the service runs.

Scope of the guarantees: they rely on POSIX semantics of link/unlink/fsync and
flock on a local filesystem shared by processes of one host (Linux in the
containers; flock is not reliable on network filesystems) and on the storage
stack below it honouring fsync (on Docker Desktop that includes the virtual
machine's disk cache policy); tests can check that the calls are made and that
failures are handled, not that data survives a real power loss. They also
assume nobody else writes inside the root; they do not defend against an
attacker who already has write access to the volume.
"""

from __future__ import annotations

import errno
import fcntl
import logging
import os
import random
import re
import stat
import tempfile
import time
import uuid
from collections.abc import Iterator
from contextlib import contextmanager
from dataclasses import dataclass, field
from pathlib import Path

INCOMING_DIR = ".incoming"
INCOMING_LOCK = ".incoming.lock"
TEMP_PREFIX = "staged-"
TEMP_SUFFIX = ".part"
DIR_MODE = 0o750
FILE_MODE = 0o640
# How long an upload waits for the reconciler to finish looking at .incoming.
INCOMING_LOCK_WAIT_SECONDS = 10.0

_UUID = r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}"
# Always used with fullmatch(): `$` would also accept a trailing newline.
KEY_PATTERN = re.compile(rf"(?P<course>{_UUID})/(?P<document>{_UUID})\.pdf")
_COURSE_DIR = re.compile(_UUID)
_STORED_FILE = re.compile(rf"{_UUID}\.pdf")
# tempfile.mkstemp names: prefix + 8 characters from [a-z0-9_] + suffix.
_TEMP_NAME = re.compile(r"staged-[a-z0-9_]{8}\.part")
_LEGACY_TEMP_NAME = re.compile(r"upload-[a-z0-9_]{8}\.part")

log = logging.getLogger(__name__)


class StorageError(Exception):
    """The file store could not complete an operation (details are for the log only)."""


class StoredFileMissing(StorageError):
    """The stored file (or its course directory) does not exist in this store."""


class StoredFileInvalid(StorageError):
    """The name exists but is not a plain file in a plain directory (e.g. a symlink)."""


def storage_key(course_id: uuid.UUID, document_id: uuid.UUID) -> str:
    """The key of a stored PDF: '<course_id>/<document_id>.pdf' (canonical lowercase UUIDs)."""
    key = f"{course_id}/{document_id}.pdf"
    if not KEY_PATTERN.fullmatch(key):  # pragma: no cover - str(UUID) is always canonical
        raise StorageError("generated an invalid storage key")
    return key


def _fsync_directory(path: Path) -> None:
    """Make the entries of a directory (names created or removed in it) durable."""
    fd = os.open(path, os.O_RDONLY | getattr(os, "O_DIRECTORY", 0))
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


def _create_directories(path: Path) -> None:
    """mkdir -p, fsyncing the parent of every level this call (or a concurrent one) created."""
    missing: list[Path] = []
    current = path
    while not os.path.lexists(current):
        missing.append(current)
        current = current.parent
    for directory in reversed(missing):
        try:
            os.mkdir(directory, DIR_MODE)
        except FileExistsError:
            pass
        _fsync_directory(directory.parent)


def _rotated(items: list, rng: random.Random | None) -> list:
    """`items` starting at a random position and wrapping around (fair bounded scans)."""
    if rng is None or len(items) < 2:
        return items
    start = rng.randrange(len(items))
    return items[start:] + items[:start]


def _close_quietly(fd: int | None) -> None:
    if fd is None:
        return
    try:
        os.close(fd)
    except OSError:
        log.warning("could not close a file descriptor", exc_info=True)


def _flock_within(fd: int, operation: int, seconds: float) -> bool:
    """flock(fd, operation) without blocking for longer than `seconds`."""
    deadline = time.monotonic() + seconds
    delay = 0.005
    while True:
        try:
            fcntl.flock(fd, operation | fcntl.LOCK_NB)
            return True
        except BlockingIOError:
            if time.monotonic() >= deadline:
                return False
            time.sleep(delay)
            delay = min(delay * 2, 0.1)


def _open_plain_file(name: str, dir_fd: int, flags: int, mode: int = 0) -> int:
    """Open a direct entry of dir_fd without following a symlink; it must be a regular file."""
    try:
        fd = os.open(name, flags | os.O_NOFOLLOW | os.O_CLOEXEC | os.O_NONBLOCK, mode, dir_fd=dir_fd)
    except FileNotFoundError:
        raise
    except OSError as exc:
        if exc.errno in (errno.ELOOP, errno.EMLINK, errno.ENOTDIR, errno.EISDIR, errno.ENXIO):
            raise StoredFileInvalid("not a plain file") from exc
        raise
    if not stat.S_ISREG(os.fstat(fd).st_mode):
        os.close(fd)
        raise StoredFileInvalid("not a plain file")
    return fd


def _open_plain_directory(name: str, dir_fd: int) -> int:
    try:
        return os.open(name, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC, dir_fd=dir_fd)
    except FileNotFoundError:
        raise
    except OSError as exc:
        if exc.errno in (errno.ELOOP, errno.ENOTDIR):
            raise StoredFileInvalid("not a plain directory") from exc
        raise


class StagedFile:
    """A file received by one upload, owned by that upload until released.

    owner_fd holds the exclusive flock that tells the reconciler the file has
    a live owner; it is closed last, after the temporary name is gone.
    """

    def __init__(self, fd: int, temp_path: Path, owner_fd: int | None = None) -> None:
        self._file = os.fdopen(fd, "wb")
        self._owner_fd = owner_fd
        self.temp_path: Path | None = temp_path  # removed by discard() unless already gone
        self.placed_path: Path | None = None  # final name created by this operation, not yet released
        self.size = 0

    def write(self, data: bytes) -> None:
        self._file.write(data)
        self.size += len(data)

    def sync(self) -> None:
        """Flush the data to disk before the file is given its final name."""
        if not self._file.closed:
            self._file.flush()
            os.fsync(self._file.fileno())
            self._file.close()

    def release(self) -> None:
        """The database now references the final file: it is no longer ours to delete."""
        self.placed_path = None

    def discard(self) -> None:
        """Close and remove the temporary name, then give up ownership. Never touches the final file.

        Runs on every exit path, so it never raises: a temporary file that
        cannot be removed is logged and left in .incoming for reconciliation
        rather than hiding the outcome of the upload.
        """
        try:
            try:
                if not self._file.closed:
                    self._file.close()
            except OSError:
                log.warning("could not close temporary upload file %s", self.temp_path, exc_info=True)
            if self.temp_path is not None:
                try:
                    os.unlink(self.temp_path)
                except FileNotFoundError:
                    pass
                except OSError:
                    log.warning(
                        "upload_reconcile temporary file %s could not be removed; left for reconciliation",
                        self.temp_path,
                        exc_info=True,
                    )
                self.temp_path = None
        finally:
            owner_fd, self._owner_fd = self._owner_fd, None
            _close_quietly(owner_fd)  # releases the ownership lock, last


@dataclass
class TempScan:
    """What clean_abandoned_temp_files() found in .incoming (names only)."""

    removed: list[str] = field(default_factory=list)
    active: list[str] = field(default_factory=list)  # locked by a live upload
    recent: list[str] = field(default_factory=list)  # younger than the grace period
    legacy: list[str] = field(default_factory=list)  # M2 names, never removed automatically
    unexpected: list[str] = field(default_factory=list)  # anything else, never touched
    truncated: bool = False


@dataclass(frozen=True)
class StoredEntry:
    key: str
    changed_at: float  # max(mtime, ctime), seconds since the epoch


class LocalFileStorage:
    """The upload store at one root directory.

    The root is pinned at first use: its fully resolved path and its identity
    (st_dev, st_ino). Every later access, path-based (`root`, used by staging
    and placement) or descriptor-based (`open_root`, used by the identity
    check, ownership locking, readers and the reconciler), first checks that
    the configured path still resolves to that same path and that the
    directory there is still that same directory. A retargeted symlink or a
    replaced mount therefore makes every operation fail with StorageError
    instead of verifying the marker in one store and writing into another.
    """

    def __init__(self, root: Path) -> None:
        self._configured_root = Path(root)
        self._root: Path | None = None
        self._root_identity: tuple[int, int] | None = None

    @property
    def configured_root(self) -> Path:
        return self._configured_root

    def _pin(self, *, create: bool) -> Path:
        if self._root is not None:
            self._check_pinned()
            return self._root
        try:
            if create:
                _create_directories(self._configured_root)
            root = self._configured_root.resolve(strict=True)
            st = os.stat(root)
        except OSError as exc:
            raise StorageError("upload directory is not available") from exc
        if not stat.S_ISDIR(st.st_mode):
            raise StorageError("upload directory is not a directory")
        self._root, self._root_identity = root, (st.st_dev, st.st_ino)
        return root

    def _check_pinned(self) -> None:
        """The configured path must still lead to the very directory pinned at first use."""
        try:
            resolved = self._configured_root.resolve(strict=True)
            st = os.lstat(self._root)
        except OSError as exc:
            raise StorageError("upload directory is not available") from exc
        if resolved != self._root:
            raise StorageError("upload directory path changed since first use (symlink retargeted?)")
        if not stat.S_ISDIR(st.st_mode) or (st.st_dev, st.st_ino) != self._root_identity:
            raise StorageError("upload directory changed since first use (mount replaced?)")

    @property
    def root(self) -> Path:
        """The pinned root directory (created on first use), checked on every access."""
        return self._pin(create=True)

    def open_root(self) -> int:
        """A descriptor of the pinned root directory, checked to be that directory. Never creates it.

        Readers (identity check, worker, reconciler) use this: a store that is
        not there must be reported as unavailable, not silently recreated.
        """
        root = self._pin(create=False)
        try:
            fd = os.open(root, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC)
        except OSError as exc:
            raise StorageError("upload directory is not available") from exc
        st = os.fstat(fd)
        if (st.st_dev, st.st_ino) != self._root_identity:
            os.close(fd)
            raise StorageError("upload directory changed since first use (mount replaced?)")
        return fd

    def _directory(self, name: str) -> Path:
        """A direct subdirectory of the root, created if missing; never a symlink."""
        path = self.root / name
        try:
            os.mkdir(path, DIR_MODE)
        except FileExistsError:
            pass
        except OSError as exc:
            raise StorageError("could not create a storage directory") from exc
        mode = os.lstat(path).st_mode
        if stat.S_ISLNK(mode) or not stat.S_ISDIR(mode):
            raise StorageError("storage directory is not a plain directory")
        return path

    @staticmethod
    def _split(key: str) -> tuple[str, str]:
        match = KEY_PATTERN.fullmatch(key)
        if match is None:
            raise StorageError("invalid storage key")
        return match["course"], f"{match['document']}.pdf"

    def _open_incoming_lock(self, root_fd: int) -> int:
        try:
            return _open_plain_file(INCOMING_LOCK, root_fd, os.O_RDWR | os.O_CREAT, FILE_MODE)
        except OSError as exc:
            raise StorageError("could not open the incoming lock") from exc

    def _create_owned_temp(self, incoming: Path) -> tuple[int, Path, int]:
        """Create a temporary file and lock it exclusively before the reconciler can look at it."""
        root_fd = self.open_root()
        try:
            lock_fd = self._open_incoming_lock(root_fd)
        finally:
            os.close(root_fd)
        try:
            if not _flock_within(lock_fd, fcntl.LOCK_SH, INCOMING_LOCK_WAIT_SECONDS):
                raise StorageError("the incoming area is locked by the reconciler")
            try:
                fd, name = tempfile.mkstemp(prefix=TEMP_PREFIX, suffix=TEMP_SUFFIX, dir=incoming)  # O_EXCL, 0600
            except OSError as exc:
                raise StorageError("could not create a temporary upload file") from exc
            owner_fd = None
            try:
                owner_fd = os.open(name, os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC)
                # Never contended: the reconciler needs .incoming.lock exclusively to see this file.
                fcntl.flock(owner_fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except OSError as exc:
                _close_quietly(owner_fd)
                _close_quietly(fd)
                try:
                    os.unlink(name)
                except OSError:
                    log.warning("upload_reconcile temporary file %s could not be removed", name, exc_info=True)
                raise StorageError("could not take ownership of a temporary upload file") from exc
            return fd, Path(name), owner_fd
        finally:
            _close_quietly(lock_fd)  # releases the shared lock

    @contextmanager
    def stage(self) -> Iterator[StagedFile]:
        """A new temporary file for one upload; its temporary name is always removed on exit."""
        incoming = self._directory(INCOMING_DIR)
        fd, temp_path, owner_fd = self._create_owned_temp(incoming)
        staged = StagedFile(fd, temp_path, owner_fd)
        try:
            try:
                os.fchmod(fd, FILE_MODE)
            except OSError as exc:
                raise StorageError("could not set the upload file mode") from exc
            yield staged
        finally:
            staged.discard()

    def place(self, staged: StagedFile, key: str) -> None:
        """Give the staged file its final name, never replacing an existing file.

        If anything fails after the link was created, staged.placed_path is
        already set, so the caller's cleanup removes exactly that file.
        """
        course_part, file_part = self._split(key)
        if staged.temp_path is None:
            raise StorageError("staged file was already discarded")
        try:
            staged.sync()
        except OSError as exc:
            raise StorageError("could not flush the uploaded file") from exc
        course_dir = self._directory(course_part)
        try:
            # The course directory's own entry must be durable before a file in it
            # is referenced, even if a concurrent upload created the directory.
            _fsync_directory(self.root)
        except OSError as exc:
            raise StorageError("could not sync the storage root") from exc
        final = course_dir / file_part
        try:
            os.link(staged.temp_path, final)
        except FileExistsError as exc:
            raise StorageError("refusing to overwrite an existing stored file") from exc
        except OSError as exc:
            raise StorageError("could not store the uploaded file") from exc
        staged.placed_path = final
        try:
            os.unlink(staged.temp_path)
            staged.temp_path = None
            _fsync_directory(course_dir)
        except OSError as exc:
            raise StorageError("could not finish storing the uploaded file") from exc

    def remove_placed(self, staged: StagedFile) -> None:
        """Delete the final file this operation created (only before release())."""
        path = staged.placed_path
        if path is None:
            return
        try:
            os.unlink(path)
        except FileNotFoundError:
            pass
        except OSError as exc:
            raise StorageError("could not remove a file left by a failed upload") from exc
        staged.placed_path = None
        try:
            _fsync_directory(path.parent)
        except OSError:
            # The unlink itself succeeded; if the removal is lost in a crash, the
            # file has no database row and reconciliation reports it.
            log.warning("could not sync the removal of %s", path, exc_info=True)

    def path_for(self, key: str) -> Path:
        """Absolute path of a stored file (diagnostics; readers use open_stored)."""
        course_part, file_part = self._split(key)
        course_dir = self.root / course_part
        try:
            mode = os.lstat(course_dir).st_mode
        except FileNotFoundError as exc:
            raise StorageError("stored file not found") from exc
        if stat.S_ISLNK(mode) or not stat.S_ISDIR(mode):
            raise StorageError("storage directory is not a plain directory")
        return course_dir / file_part

    # --- readers (worker, reconciler) -------------------------------------------------

    def open_stored(self, key: str) -> int:
        """Open a stored file read-only and return its descriptor (the caller closes it).

        Only names generated by storage_key() are accepted; neither the course
        directory nor the file may be a symlink, and the file must be a regular
        file. StoredFileMissing: no such file in this store. StoredFileInvalid:
        something else is at that name. StorageError: the store itself failed.
        """
        course_part, file_part = self._split(key)
        root_fd = self.open_root()
        course_fd = None
        try:
            try:
                course_fd = _open_plain_directory(course_part, root_fd)
                return _open_plain_file(file_part, course_fd, os.O_RDONLY)
            except FileNotFoundError as exc:
                raise StoredFileMissing("stored file not found") from exc
            except StoredFileInvalid:
                raise
            except OSError as exc:
                raise StorageError("could not open the stored file") from exc
        finally:
            _close_quietly(course_fd)
            os.close(root_fd)

    def stored_file_state(self, key: str) -> str:
        """'present', 'missing' or 'invalid' (StorageError when the store itself fails)."""
        try:
            fd = self.open_stored(key)
        except StoredFileMissing:
            return "missing"
        except StoredFileInvalid:
            return "invalid"
        os.close(fd)
        return "present"

    def stored_file_in_use(self, key: str) -> bool:
        """True while an upload still owns the file (holds its lock); False otherwise."""
        try:
            fd = self.open_stored(key)
        except (StoredFileMissing, StoredFileInvalid):
            return False
        try:
            try:
                fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError:
                return True
            return False
        finally:
            os.close(fd)  # releases the probe lock

    def iter_stored_files(self, limit: int, rng: random.Random | None = None) -> Iterator[StoredEntry]:
        """Stored originals (<course uuid>/<document uuid>.pdf), never following symlinks.

        Entries with other names are skipped (they are not ours to interpret).
        At most `limit` entries are yielded. With `rng`, the scan starts at a
        random course and file and wraps around, so that repeated bounded
        scans of a large store do not always stop at the same entries.
        """
        root_fd = self.open_root()
        try:
            count = 0
            for course in _rotated(sorted(os.listdir(root_fd)), rng):
                if not _COURSE_DIR.fullmatch(course):
                    continue
                try:
                    course_fd = _open_plain_directory(course, root_fd)
                except (FileNotFoundError, StoredFileInvalid):
                    continue
                try:
                    for name in _rotated(sorted(os.listdir(course_fd)), rng):
                        if not _STORED_FILE.fullmatch(name):
                            continue
                        try:
                            st = os.stat(name, dir_fd=course_fd, follow_symlinks=False)
                        except FileNotFoundError:
                            continue
                        if not stat.S_ISREG(st.st_mode):
                            continue
                        yield StoredEntry(key=f"{course}/{name}", changed_at=max(st.st_mtime, st.st_ctime))
                        count += 1
                        if count >= limit:
                            return
                finally:
                    os.close(course_fd)
        finally:
            os.close(root_fd)

    def clean_abandoned_temp_files(
        self,
        *,
        grace_seconds: float,
        limit: int,
        lock_wait_seconds: float = 2.0,
        rng: random.Random | None = None,
    ) -> TempScan | None:
        """Remove temporary files whose upload is provably gone; report everything else.

        Returns None when .incoming.lock could not be taken in time (uploads
        are creating files): nothing is examined then. See the module
        docstring for the protocol that makes removal safe. When there are more
        entries than `limit`, the examined window starts at a random entry
        (with `rng`) and wraps around.
        """
        scan = TempScan()
        root_fd = self.open_root()
        try:
            lock_fd = self._open_incoming_lock(root_fd)
            try:
                if not _flock_within(lock_fd, fcntl.LOCK_EX, lock_wait_seconds):
                    return None
                try:
                    incoming_fd = _open_plain_directory(INCOMING_DIR, root_fd)
                except FileNotFoundError:
                    return scan
                except StoredFileInvalid as exc:
                    raise StorageError(".incoming is not a plain directory") from exc
                try:
                    names = sorted(os.listdir(incoming_fd))
                    if len(names) > limit:
                        names, scan.truncated = _rotated(names, rng)[:limit], True
                    now = time.time()
                    for name in names:
                        self._examine_temp(incoming_fd, name, now, grace_seconds, scan)
                finally:
                    os.close(incoming_fd)
            finally:
                _close_quietly(lock_fd)  # releases the exclusive lock
        finally:
            os.close(root_fd)
        return scan

    @staticmethod
    def _examine_temp(incoming_fd: int, name: str, now: float, grace_seconds: float, scan: TempScan) -> None:
        if _LEGACY_TEMP_NAME.fullmatch(name):
            scan.legacy.append(name)
            return
        if not _TEMP_NAME.fullmatch(name):
            scan.unexpected.append(name)
            return
        try:
            fd = _open_plain_file(name, incoming_fd, os.O_RDONLY)
        except FileNotFoundError:
            return  # its upload removed it a moment ago
        except StoredFileInvalid:
            scan.unexpected.append(name)
            return
        try:
            opened = os.fstat(fd)
            # Age is a margin on top of the lock protocol, not the proof: the
            # last write (mtime) is what an upload in progress keeps moving.
            if now - opened.st_mtime < grace_seconds:
                scan.recent.append(name)
                return
            try:
                fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError:
                scan.active.append(name)
                return
            try:
                current = os.stat(name, dir_fd=incoming_fd, follow_symlinks=False)
            except FileNotFoundError:
                return
            if (current.st_dev, current.st_ino) != (opened.st_dev, opened.st_ino):
                scan.unexpected.append(name)  # replaced since it was opened: leave it alone
                return
            os.unlink(name, dir_fd=incoming_fd)
            scan.removed.append(name)
        finally:
            os.close(fd)
